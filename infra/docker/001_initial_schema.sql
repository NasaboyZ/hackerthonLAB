CREATE SCHEMA IF NOT EXISTS players;
CREATE SCHEMA IF NOT EXISTS findings;
CREATE SCHEMA IF NOT EXISTS exploration;
CREATE SCHEMA IF NOT EXISTS geo;
CREATE SCHEMA IF NOT EXISTS regulations;

CREATE TABLE IF NOT EXISTS geo.waterbodies (
  id uuid PRIMARY KEY,
  external_id text,
  source_dataset text NOT NULL,
  name text,
  waterbody_type text,
  geometry geometry(Geometry, 4326),
  source_version text,
  imported_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_waterbodies_geometry_gist ON geo.waterbodies USING gist (geometry);
CREATE INDEX IF NOT EXISTS ix_waterbodies_source_external ON geo.waterbodies (source_dataset, external_id);

