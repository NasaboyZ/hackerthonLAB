CREATE TABLE IF NOT EXISTS identity.roles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name varchar(256), normalized_name varchar(256), concurrency_stamp text
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_identity_roles_normalized_name ON identity.roles (normalized_name);
CREATE TABLE IF NOT EXISTS identity.user_claims (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE, claim_type text, claim_value text);
CREATE INDEX IF NOT EXISTS ix_identity_user_claims_user_id ON identity.user_claims (user_id);
CREATE TABLE IF NOT EXISTS identity.user_logins (login_provider varchar(128) NOT NULL, provider_key varchar(128) NOT NULL, provider_display_name text, user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE, PRIMARY KEY (login_provider, provider_key));
CREATE INDEX IF NOT EXISTS ix_identity_user_logins_user_id ON identity.user_logins (user_id);
CREATE TABLE IF NOT EXISTS identity.user_roles (user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE, role_id uuid NOT NULL REFERENCES identity.roles(id) ON DELETE CASCADE, PRIMARY KEY (user_id, role_id));
CREATE INDEX IF NOT EXISTS ix_identity_user_roles_role_id ON identity.user_roles (role_id);
CREATE TABLE IF NOT EXISTS identity.user_tokens (user_id uuid NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE, login_provider varchar(128) NOT NULL, name varchar(128) NOT NULL, value text, PRIMARY KEY (user_id, login_provider, name));
CREATE TABLE IF NOT EXISTS identity.role_claims (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_id uuid NOT NULL REFERENCES identity.roles(id) ON DELETE CASCADE, claim_type text, claim_value text);
CREATE INDEX IF NOT EXISTS ix_identity_role_claims_role_id ON identity.role_claims (role_id);

CREATE TABLE IF NOT EXISTS players.profiles (
  user_id uuid PRIMARY KEY,
  username varchar(32) NOT NULL,
  level integer NOT NULL DEFAULT 1 CHECK (level >= 1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_profiles_username_ci ON players.profiles (lower(username));

CREATE TABLE IF NOT EXISTS findings.finds (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_user_id uuid NOT NULL,
  title varchar(120) NOT NULL,
  description text,
  category varchar(40),
  found_at timestamptz NOT NULL,
  location geometry(Point, 4326),
  weight_grams integer CHECK (weight_grams IS NULL OR weight_grams >= 0),
  visibility varchar(20) NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_finds_location_gist ON findings.finds USING gist (location);

CREATE TABLE IF NOT EXISTS findings.media (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  finding_id uuid NOT NULL REFERENCES findings.finds(id) ON DELETE CASCADE,
  storage_key varchar(512) NOT NULL
);

CREATE TABLE IF NOT EXISTS exploration.spots (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_user_id uuid NOT NULL,
  name varchar(120) NOT NULL DEFAULT 'Unbenannter Spot',
  location geometry(Point, 4326) NOT NULL,
  visibility varchar(20) NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_spots_location_gist ON exploration.spots USING gist (location);
ALTER TABLE exploration.spots ADD COLUMN IF NOT EXISTS name varchar(120) NOT NULL DEFAULT 'Unbenannter Spot';

CREATE TABLE IF NOT EXISTS exploration.tracks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_user_id uuid NOT NULL,
  path geometry(LineString, 4326) NOT NULL,
  visibility varchar(20) NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  started_at timestamptz NOT NULL,
  ended_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (ended_at >= started_at)
);
CREATE INDEX IF NOT EXISTS ix_tracks_path_gist ON exploration.tracks USING gist (path);

CREATE TABLE IF NOT EXISTS exploration.areas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_user_id uuid NOT NULL,
  name varchar(120) NOT NULL DEFAULT 'Unbenanntes Suchgebiet',
  boundary geometry(MultiPolygon, 4326) NOT NULL,
  visibility varchar(20) NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_areas_boundary_gist ON exploration.areas USING gist (boundary);
ALTER TABLE exploration.areas ADD COLUMN IF NOT EXISTS name varchar(120) NOT NULL DEFAULT 'Unbenanntes Suchgebiet';

CREATE TABLE IF NOT EXISTS regulations.rules (
  id uuid PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL,
  classification varchar(32) NOT NULL CHECK (classification IN ('PROHIBITED', 'RESTRICTED', 'UNKNOWN', 'INFORMATION_ONLY')),
  verification_status varchar(32) NOT NULL CHECK (verification_status IN ('verified', 'pending')),
  jurisdiction varchar(120) NOT NULL,
  authority_name varchar(240) NOT NULL,
  source_publication_date date,
  last_verified_at timestamptz,
  valid_from date,
  valid_until date,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);
CREATE INDEX IF NOT EXISTS ix_rules_status_jurisdiction ON regulations.rules (verification_status, jurisdiction);

CREATE TABLE IF NOT EXISTS regulations.sources (
  id uuid PRIMARY KEY,
  rule_id uuid NOT NULL REFERENCES regulations.rules(id) ON DELETE CASCADE,
  authority_name varchar(240) NOT NULL,
  source_url varchar(1000) NOT NULL CHECK (source_url ~ '^https://'),
  source_label varchar(240)
);
CREATE INDEX IF NOT EXISTS ix_sources_rule_id ON regulations.sources (rule_id);

CREATE TABLE IF NOT EXISTS regulations.zones (
  id uuid PRIMARY KEY,
  rule_id uuid NOT NULL REFERENCES regulations.rules(id) ON DELETE CASCADE,
  geometry geometry(MultiPolygon, 4326),
  geometry_source varchar(240) NOT NULL,
  geometry_verification_status varchar(32) NOT NULL CHECK (geometry_verification_status IN ('verified', 'pending')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_zones_geometry_gist ON regulations.zones USING gist (geometry);

